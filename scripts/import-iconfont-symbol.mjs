import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = process.argv[2];

if (!sourceDirectory) {
  throw new Error(
    'Usage: node scripts/import-iconfont-symbol.mjs <iconfont-download-directory>',
  );
}

const sourceScript = path.resolve(sourceDirectory, 'iconfont.js');
const sourceMetadata = path.resolve(sourceDirectory, 'iconfont.json');
const iconNameRegistry = path.join(
  repositoryRoot,
  'fonted-oa',
  'src',
  'components',
  'IconFont.tsx',
);

const [rawScript, rawMetadata, rawIconNameRegistry] = await Promise.all([
  readFile(sourceScript, 'utf8'),
  readFile(sourceMetadata, 'utf8'),
  readFile(iconNameRegistry, 'utf8'),
]);

const metadata = JSON.parse(rawMetadata);
const availableNames = new Set(metadata.glyphs.map((glyph) => glyph.font_class));
const registryMatch = rawIconNameRegistry.match(
  /export const iconFontNames = \[([\s\S]*?)\] as const;/,
);
if (!registryMatch) {
  throw new Error('Cannot read iconFontNames from the OA registry.');
}
const requiredNames = [
  ...registryMatch[1].matchAll(/'([^']+)'/g),
].map((match) => match[1]);
const missingNames = requiredNames.filter((name) => !availableNames.has(name));
if (missingNames.length) {
  throw new Error(
    `The downloaded Iconfont package is missing: ${missingNames.join(', ')}`,
  );
}

const colorPreservedNames = new Set([
  'main_icon',
  'CSV',
  'PDF',
  'PNG',
  'JPG',
  'TXT',
]);
const monochromeNames = new Set(
  [...availableNames].filter((name) => !colorPreservedNames.has(name)),
);

let normalizedScript = rawScript;
for (const name of monochromeNames) {
  const symbolPattern = new RegExp(
    `(<symbol\\s+id="icon-${name}"[\\s\\S]*?<\\/symbol>)`,
  );
  const symbolMatch = normalizedScript.match(symbolPattern);
  if (!symbolMatch) {
    throw new Error(`Cannot find #icon-${name} in iconfont.js.`);
  }
  const normalizedSymbol = symbolMatch[1].replace(
    /\sfill="[^"]*"/g,
    ' fill="currentColor"',
  );
  normalizedScript = normalizedScript.replace(symbolMatch[1], normalizedSymbol);
}

const targets = [
  path.join(repositoryRoot, 'fronted-main', 'public', 'iconfont'),
  path.join(repositoryRoot, 'fonted-oa', 'public', 'iconfont'),
];
const version = createHash('sha256')
  .update(normalizedScript)
  .digest('hex')
  .slice(0, 12);
const generatedVersionSource =
  `// Generated by scripts/import-iconfont-symbol.mjs.\n`
  + `export const iconfontVersion = '${version}' as const;\n`;

await Promise.all(
  targets.flatMap((targetDirectory) => [
    writeFile(path.join(targetDirectory, 'iconfont.js'), normalizedScript, 'utf8'),
    writeFile(path.join(targetDirectory, 'iconfont.json'), rawMetadata, 'utf8'),
  ]),
);
await Promise.all([
  writeFile(
    path.join(
      repositoryRoot,
      'fronted-main',
      'src',
      'generated',
      'iconfontVersion.ts',
    ),
    generatedVersionSource,
    'utf8',
  ),
  writeFile(
    path.join(
      repositoryRoot,
      'fonted-oa',
      'src',
      'generated',
      'iconfontVersion.ts',
    ),
    generatedVersionSource,
    'utf8',
  ),
]);

process.stdout.write(
  `Imported ${availableNames.size} Iconfont symbols into ${targets.length} frontend apps (${version}).\n`,
);
